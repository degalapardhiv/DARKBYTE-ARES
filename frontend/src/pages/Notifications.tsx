import { useCallback, useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import {
  AlertTriangle,
  Bell,
  BellOff,
  CheckCheck,
  CheckCircle2,
  ChevronRight,
  Info,
  RefreshCw,
  ShieldAlert,
  Trash2,
} from "lucide-react";
import { PageHeader } from "../components/PageHeader";
import { Panel, EmptyState, ErrorState, PageLoader, Pagination } from "../components/ui";
import { ConfirmDialog } from "../components/Modal";
import { api } from "../lib/api";
import type { Notification } from "../lib/types";
import { useToast } from "../context/ToastContext";
import { cn, timeAgo } from "../lib/utils";

const LEVEL_STYLES: Record<string, { icon: typeof Info; color: string; bg: string }> = {
  info: { icon: Info, color: "#00E5FF", bg: "rgba(0,229,255,0.08)" },
  success: { icon: CheckCircle2, color: "#00FF88", bg: "rgba(0,255,136,0.08)" },
  warning: { icon: AlertTriangle, color: "#FFB020", bg: "rgba(255,176,32,0.08)" },
  error: { icon: ShieldAlert, color: "#FF3B5C", bg: "rgba(255,59,92,0.08)" },
  critical: { icon: ShieldAlert, color: "#FF3B5C", bg: "rgba(255,59,92,0.1)" },
};

export function Notifications() {
  const navigate = useNavigate();
  const { notify } = useToast();
  const [items, setItems] = useState<Notification[]>([]);
  const [total, setTotal] = useState(0);
  const [unread, setUnread] = useState(0);
  const [limit] = useState(25);
  const [offset, setOffset] = useState(0);
  const [unreadOnly, setUnreadOnly] = useState(false);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [refreshing, setRefreshing] = useState(false);
  const [busyId, setBusyId] = useState<string | null>(null);
  const [pendingDelete, setPendingDelete] = useState<Notification | null>(null);

  const load = useCallback(async (silent = false) => {
    if (!silent) setRefreshing(true);
    try {
      const response = await api.notifications.list({ unread_only: unreadOnly, limit, offset });
      setItems(response.items);
      setTotal(response.total);
      setUnread(response.unread);
      setError(null);
    } catch (reason) {
      setError(reason instanceof Error ? reason.message : "Could not load notifications.");
    } finally {
      setLoading(false);
      setRefreshing(false);
    }
  }, [unreadOnly, limit, offset]);

  useEffect(() => {
    void load();
  }, [load]);

  const markRead = async (notification: Notification) => {
    if (notification.read) {
      if (notification.link) navigate(notification.link);
      return;
    }
    setBusyId(notification.id);
    try {
      await api.notifications.read(notification.id);
      setItems((current) => current.map((item) => (item.id === notification.id ? { ...item, read: true } : item)));
      setUnread((value) => Math.max(0, value - 1));
      if (notification.link) navigate(notification.link);
    } catch (reason) {
      notify({ title: "Could not mark notification read", message: reason instanceof Error ? reason.message : "Request failed.", tone: "error" });
    } finally {
      setBusyId(null);
    }
  };

  const markAll = async () => {
    try {
      const response = await api.notifications.readAll();
      notify({ title: "Notifications updated", message: `${response.updated} alert(s) marked read.`, tone: "success" });
      await load(true);
    } catch (reason) {
      notify({ title: "Could not update notifications", message: reason instanceof Error ? reason.message : "Request failed.", tone: "error" });
    }
  };

  const remove = async () => {
    if (!pendingDelete) return;
    try {
      await api.notifications.remove(pendingDelete.id);
      notify({ title: "Notification removed", tone: "success" });
      if (!pendingDelete.read) setUnread((value) => Math.max(0, value - 1));
      setPendingDelete(null);
      await load(true);
    } catch (reason) {
      notify({ title: "Could not remove notification", message: reason instanceof Error ? reason.message : "Request failed.", tone: "error" });
    }
  };

  if (loading) return <PageLoader label="Loading notification inbox" />;

  return (
    <div>
      <PageHeader
        eyebrow="Operator inbox"
        title="Notifications"
        description="Operational alerts generated by assessment completion, findings and platform events. Read receipts and removals are recorded in the audit chain."
        actions={
          <>
            <button className="btn-ghost" onClick={() => void load()} disabled={refreshing}>
              <RefreshCw size={14} className={refreshing ? "animate-spin" : ""} /> Refresh
            </button>
            {unread > 0 ? (
              <button className="btn-primary" onClick={() => void markAll()}>
                <CheckCheck size={15} /> Mark all read
              </button>
            ) : null}
          </>
        }
      />

      <div className="mb-4 flex flex-wrap items-center gap-2">
        <button
          onClick={() => {
            setUnreadOnly(false);
            setOffset(0);
          }}
          className={cn("chip px-3 py-1.5 transition", !unreadOnly && "border-cyan/30 bg-cyan/5 text-cyan")}
        >
          <Bell size={11} /> All alerts <span className="text-slate-600">{unreadOnly ? "" : total}</span>
        </button>
        <button
          onClick={() => {
            setUnreadOnly(true);
            setOffset(0);
          }}
          className={cn("chip px-3 py-1.5 transition", unreadOnly && "border-amber/30 bg-amber/5 text-amber")}
        >
          <BellOff size={11} /> Unread <span className={unread ? "text-amber" : "text-slate-600"}>{unread}</span>
        </button>
        <span className="ml-auto font-mono text-[9px] uppercase tracking-wider text-slate-600">
          {unread} unread · {total} retained
        </span>
      </div>

      {error ? (
        <ErrorState message={error} onRetry={() => void load()} />
      ) : !items.length ? (
        <Panel>
          <EmptyState
            icon={BellOff}
            title={unreadOnly ? "No unread notifications" : "Inbox clear"}
            description="New assessment completions, critical findings and platform events will appear here."
          />
        </Panel>
      ) : (
        <div className="space-y-2">
          {items.map((notification) => {
            const style = LEVEL_STYLES[notification.level] || LEVEL_STYLES.info;
            const Icon = style.icon;
            return (
              <Panel
                key={notification.id}
                className={cn(
                  "flex items-start gap-3 p-4 transition",
                  !notification.read && "border-cyan/20 bg-cyan/[0.025]",
                )}
              >
                <span
                  className="flex h-9 w-9 shrink-0 items-center justify-center rounded-xl border"
                  style={{ color: style.color, backgroundColor: style.bg, borderColor: `${style.color}28` }}
                >
                  <Icon size={16} />
                </span>
                <div className="min-w-0 flex-1">
                  <div className="flex flex-wrap items-center gap-2">
                    <p className={cn("text-xs", notification.read ? "font-medium text-ice" : "font-semibold text-white")}>
                      {notification.title}
                    </p>
                    {!notification.read ? <span className="h-1.5 w-1.5 rounded-full bg-cyan shadow-[0_0_8px_#00E5FF]" /> : null}
                    <span className="ml-auto font-mono text-[8px] uppercase tracking-wider text-slate-600">
                      {timeAgo(notification.created_at)}
                    </span>
                  </div>
                  <p className="mt-1.5 text-[11px] leading-relaxed text-mist">{notification.message}</p>
                  <div className="mt-2 flex flex-wrap items-center gap-2">
                    {notification.link ? (
                      <button
                        className="inline-flex items-center gap-1 font-mono text-[9px] uppercase tracking-wider text-cyan/80 transition hover:text-cyan disabled:opacity-50"
                        onClick={() => void markRead(notification)}
                        disabled={busyId === notification.id}
                      >
                        Open resource <ChevronRight size={11} />
                      </button>
                    ) : null}
                    {!notification.read ? (
                      <button
                        className="inline-flex items-center gap-1 font-mono text-[9px] uppercase tracking-wider text-mist transition hover:text-white disabled:opacity-50"
                        onClick={() => void markRead(notification)}
                        disabled={busyId === notification.id}
                      >
                        <CheckCircle2 size={11} /> Mark read
                      </button>
                    ) : (
                      <span className="inline-flex items-center gap-1 font-mono text-[9px] uppercase tracking-wider text-slate-600">
                        <CheckCheck size={11} /> read
                      </span>
                    )}
                  </div>
                </div>
                <button
                  className="shrink-0 rounded-md border border-line p-1.5 text-mist transition hover:border-crimson/40 hover:text-crimson"
                  onClick={() => setPendingDelete(notification)}
                  aria-label="Delete notification"
                >
                  <Trash2 size={12} />
                </button>
              </Panel>
            );
          })}
          <Panel className="overflow-hidden">
            <Pagination total={total} limit={limit} offset={offset} onChange={setOffset} />
          </Panel>
        </div>
      )}

      <ConfirmDialog
        open={Boolean(pendingDelete)}
        title="Remove notification?"
        description={`"${pendingDelete?.title}" will be removed from your inbox. This action is audited.`}
        confirmLabel="Remove"
        danger
        onConfirm={() => void remove()}
        onClose={() => setPendingDelete(null)}
      />
    </div>
  );
}
